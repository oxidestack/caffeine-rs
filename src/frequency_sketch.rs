//! A probabilistic multiset for estimating the popularity of an element within a time window.
//!
//! Faithful port of `upstream/caffeine/src/main/java/com/github/benmanes/caffeine/cache/FrequencySketch.java`
//! (Caffeine v3.1.8). The maximum frequency of an element is limited to 15 (4 bits) and an aging
//! process periodically halves the popularity of all elements.
//!
//! This is the admission filter for the W-TinyLFU eviction policy (see `crate::eviction`). Eviction
//! is per-node (Infinispan, the consumer, keeps it per node, nothing about
//! it goes on the wire), so this port has no wire-compatibility obligation — only the same probabilistic
//! properties Caffeine guarantees. Because Rust has no `Object.hashCode()`, elements are hashed with
//! `std::hash::Hash` via a fixed-seed `DefaultHasher` truncated to 32 bits, standing in for Java's
//! `hashCode()`; the sketch's internal bit manipulation (`spread`, `rehash`, block/counter layout,
//! `reset`) is ported bit-for-bit.
//!
//! This class maintains a 4-bit CountMinSketch with periodic aging to provide the popularity history
//! for the TinyLFU admission policy. The counter matrix is a single-dimensional array holding 16
//! counters per slot; a fixed depth of four balances accuracy and cost, resulting in a width of four
//! times the length of the array. The array's length equals the maximum number of entries in the
//! cache, rounded up to the closest power of two. This gives a confidence of 93.75% and an error
//! bound of e / width. Items are distributed to 64-byte blocks (one L1 cache line), and each of the
//! four counters is drawn from a distinct 16-byte segment within its block.
//!
//! References: An Improved Data Stream Summary: The Count-Min Sketch and its Applications
//! (<http://dimacs.rutgers.edu/~graham/pubs/papers/cm-full.pdf>); TinyLFU: A Highly Efficient Cache
//! Admission Policy (<https://dl.acm.org/citation.cfm?id=3149371>).
//!
//! Cross-checked bit-for-bit against reference vectors generated by running the actual pinned
//! `caffeine-3.1.8.jar` (`upstream-tools/generate.sh` → `tests/vectors/frequency_sketch_*`), not a
//! recompiled-from-source approximation; see the `vectors` test module at the bottom of this file.

use std::marker::PhantomData;

/// Produces the same 32-bit hash code Java's boxed numeric wrapper types return from `hashCode()`.
/// `FrequencySketch<E>` only ever calls `e.hashCode()` (FrequencySketch.java:125, 151), and Java's
/// `Integer`/`Long` wrappers define that identically to their value (`Integer.hashCode()` returns the
/// int itself; `Long.hashCode()` returns `(int) (value ^ (value >>> 32))`) — implementing the same
/// rule here, instead of hashing with `std::hash::Hash`, is what makes the reference vectors below
/// (generated with `Integer` keys against the real jar) comparable bit-for-bit rather than merely
/// structurally.
pub trait JavaHashCode {
    /// The value Java's `hashCode()` returns for the same value boxed.
    fn java_hash_code(&self) -> i32;
}

impl JavaHashCode for i32 {
    fn java_hash_code(&self) -> i32 {
        *self
    }
}

impl JavaHashCode for u32 {
    fn java_hash_code(&self) -> i32 {
        *self as i32
    }
}

impl JavaHashCode for i64 {
    fn java_hash_code(&self) -> i32 {
        let v = *self as u64;
        (v ^ (v >> 32)) as i32
    }
}

impl JavaHashCode for u64 {
    fn java_hash_code(&self) -> i32 {
        let v = *self;
        (v ^ (v >> 32)) as i32
    }
}

/// Upstream `FrequencySketch.RESET_MASK` (FrequencySketch.java:66).
const RESET_MASK: u64 = 0x7777_7777_7777_7777;
/// Upstream `FrequencySketch.ONE_MASK` (FrequencySketch.java:67).
const ONE_MASK: u64 = 0x1111_1111_1111_1111;

/// Port of `Caffeine.ceilingPowerOfTwo(int)` (Caffeine.java:208-211): the smallest power of two
/// greater than or equal to `x`. From Hacker's Delight, Chapter 3 (Harry S. Warren Jr.).
fn ceiling_power_of_two(x: i32) -> i32 {
    let nlz = (x - 1).leading_zeros();
    1i32.wrapping_shl(u32::wrapping_neg(nlz))
}

/// Applies a supplemental hash function to defend against a poor quality hash.
/// Port of `FrequencySketch.spread(int)` (FrequencySketch.java:172-179).
fn spread(x: i32) -> i32 {
    let mut x = x as u32;
    x ^= x >> 17;
    x = x.wrapping_mul(0xed5a_d4bb);
    x ^= x >> 11;
    x = x.wrapping_mul(0xac4c_1b51);
    x ^= x >> 15;
    x as i32
}

/// Applies another round of hashing for additional randomization.
/// Port of `FrequencySketch.rehash(int)` (FrequencySketch.java:182-186).
fn rehash(x: i32) -> i32 {
    let mut x = x as u32;
    x = x.wrapping_mul(0x3184_8bab);
    x ^= x >> 14;
    x as i32
}

/// A probabilistic multiset for estimating the popularity of an element within a time window.
///
/// Port of `FrequencySketch<E>` (FrequencySketch.java:29). Lazily initialized: [`Self::new`] returns
/// an uninitialized sketch (matching the no-arg Java constructor); [`Self::ensure_capacity`] must be
/// called before [`Self::increment`]/[`Self::frequency`] do anything useful, exactly as upstream.
#[derive(Debug)]
pub struct FrequencySketch<E> {
    sample_size: i32,
    block_mask: i32,
    table: Option<Vec<u64>>,
    size: i32,
    _marker: PhantomData<fn(&E)>,
}

impl<E: JavaHashCode> Default for FrequencySketch<E> {
    fn default() -> Self {
        Self::new()
    }
}

impl<E: JavaHashCode> FrequencySketch<E> {
    /// Creates a lazily initialized frequency sketch, requiring [`Self::ensure_capacity`] be called
    /// when the maximum size of the cache has been determined. Port of the no-arg constructor
    /// (FrequencySketch.java:79).
    pub fn new() -> Self {
        Self { sample_size: 0, block_mask: 0, table: None, size: 0, _marker: PhantomData }
    }

    /// Initializes and increases the capacity of this sketch, if necessary, to ensure it can
    /// accurately estimate the popularity of elements given the maximum size of the cache. This
    /// operation forgets all previous counts when resizing.
    ///
    /// Port of `ensureCapacity(long)` (FrequencySketch.java:88-102).
    ///
    /// # Panics
    /// Panics if `maximum_size` is negative, matching upstream's `requireArgument` /
    /// `IllegalArgumentException`.
    pub fn ensure_capacity(&mut self, maximum_size: i64) {
        assert!(maximum_size >= 0, "maximum_size must not be negative: {maximum_size}");
        let maximum = maximum_size.min((i32::MAX >> 1) as i64) as i32;
        if let Some(table) = &self.table
            && table.len() as i32 >= maximum
        {
            return;
        }

        let len = ceiling_power_of_two(maximum).max(8);
        self.table = Some(vec![0u64; len as usize]);
        // Port of `sampleSize = (maximumSize == 0) ? 10 : (10 * maximum);` (FrequencySketch.java:96):
        // Java int multiplication wraps on overflow, which is exactly what feeds the `sampleSize <= 0`
        // fallback below, so this uses `wrapping_mul` rather than a saturating one.
        self.sample_size = if maximum_size == 0 { 10 } else { 10i32.wrapping_mul(maximum) };
        self.block_mask = (len >> 3) - 1;
        if self.sample_size <= 0 {
            self.sample_size = i32::MAX;
        }
        self.size = 0;
    }

    /// Returns whether the sketch has not yet been initialized.
    /// Port of `isNotInitialized()` (FrequencySketch.java:108-110).
    pub fn is_not_initialized(&self) -> bool {
        self.table.is_none()
    }

    /// Returns the estimated number of occurrences of an element, up to the maximum (15).
    /// Port of `frequency(E)` (FrequencySketch.java:119-135).
    pub fn frequency(&self, e: &E) -> i32 {
        let Some(table) = &self.table else {
            return 0;
        };

        let mut count = [0i32; 4];
        let block_hash = spread(e.java_hash_code());
        let counter_hash = rehash(block_hash) as u32;
        let block = ((block_hash & self.block_mask) as usize) << 3;
        for (i, slot) in count.iter_mut().enumerate() {
            let h = counter_hash >> (i << 3);
            let index = (h >> 1) & 15;
            let offset = h & 1;
            let table_index = block + (offset as usize) + (i << 1);
            *slot = ((table[table_index] >> (index << 2)) & 0xf) as i32;
        }
        count[0].min(count[1]).min(count[2].min(count[3]))
    }

    /// Increments the popularity of the element if it does not exceed the maximum (15). The
    /// popularity of all elements is periodically down-sampled when observed events exceed a
    /// threshold, aging the history so long-idle entries fade away.
    ///
    /// Port of `increment(E)` (FrequencySketch.java:145-169). The four `incrementAt` calls
    /// deliberately use non-short-circuiting `|` in upstream so all four counters are always
    /// touched; this port preserves that with Rust's bitwise-or on `bool`.
    pub fn increment(&mut self, e: &E) {
        self.increment_hash(e.java_hash_code());
    }

    /// [`Self::increment`] of an element whose `hashCode()` is `hash_code`: what the eviction policy
    /// uses for a key it only knows by hash (the retired-key sentinel, see `eviction.rs`).
    pub fn increment_hash(&mut self, hash_code: i32) {
        if self.table.is_none() {
            return;
        }

        let block_hash = spread(hash_code);
        let counter_hash = rehash(block_hash) as u32;
        let block = ((block_hash & self.block_mask) as usize) << 3;
        let mut index = [0usize; 4];
        let mut table_index = [0usize; 4];
        for i in 0..4 {
            let h = counter_hash >> (i << 3);
            index[i] = ((h >> 1) & 15) as usize;
            let offset = (h & 1) as usize;
            table_index[i] = block + offset + (i << 1);
        }

        let added = self.increment_at(table_index[0], index[0])
            | self.increment_at(table_index[1], index[1])
            | self.increment_at(table_index[2], index[2])
            | self.increment_at(table_index[3], index[3]);

        if added {
            self.size += 1;
            if self.size == self.sample_size {
                self.reset();
            }
        }
    }

    /// Increments the specified counter by 1 if it is not already at the maximum value (15).
    /// Port of `incrementAt(int, int)` (FrequencySketch.java:195-203).
    fn increment_at(&mut self, i: usize, j: usize) -> bool {
        let table = self.table.as_mut().expect("initialized");
        let offset = j << 2;
        let mask = 0xfu64 << offset;
        if (table[i] & mask) != mask {
            table[i] += 1u64 << offset;
            true
        } else {
            false
        }
    }

    /// Reduces every counter by half of its original value.
    /// Port of `reset()` (FrequencySketch.java:206-213).
    fn reset(&mut self) {
        let table = self.table.as_mut().expect("initialized");
        let mut count = 0i32;
        for slot in table.iter_mut() {
            count += (*slot & ONE_MASK).count_ones() as i32;
            *slot = (*slot >> 1) & RESET_MASK;
        }
        self.size = (self.size - (count >> 2)) >> 1;
    }

    #[cfg(test)]
    fn table_len(&self) -> usize {
        self.table.as_ref().map_or(0, |t| t.len())
    }

    /// Port of `FrequencySketch.sampleSize` (FrequencySketch.java field), read by `climb()`'s
    /// `determineAdjustment()` (BoundedLocalCache.java:1146) to gate hill-climbing on having enough
    /// samples. `pub(crate)` rather than `#[cfg(test)]`: `eviction::BoundedCache` needs it outside tests.
    pub(crate) fn sample_size(&self) -> i32 {
        self.sample_size
    }

    #[cfg(test)]
    fn block_mask(&self) -> i32 {
        self.block_mask
    }

    #[cfg(test)]
    fn size(&self) -> i32 {
        self.size
    }
}

#[cfg(test)]
mod tests {
    //! Port of `FrequencySketchTest.java` (upstream test suite), adapted to Rust: `Integer` items stay
    //! `i32` (so `java_hash_code()` matches Java's `Integer.hashCode()` identity exactly, see
    //! `JavaHashCode` above), TestNG's `@DataProvider` becomes a plain helper, Truth assertions become
    //! `assert_eq!`/`assert!`.

    use super::FrequencySketch;

    fn make_sketch(maximum_size: i64) -> FrequencySketch<i32> {
        let mut sketch = FrequencySketch::new();
        sketch.ensure_capacity(maximum_size);
        sketch
    }

    /// Port of `construct()` (FrequencySketchTest.java:32-40).
    #[test]
    fn construct() {
        let mut sketch: FrequencySketch<i32> = FrequencySketch::new();
        assert_eq!(sketch.table_len(), 0);
        assert!(sketch.is_not_initialized());

        sketch.increment(&42);
        assert_eq!(sketch.frequency(&42), 0);
    }

    /// Port of `ensureCapacity_negative` (FrequencySketchTest.java:42-45).
    #[test]
    #[should_panic(expected = "must not be negative")]
    fn ensure_capacity_negative() {
        let mut sketch = make_sketch(512);
        sketch.ensure_capacity(-1);
    }

    /// Port of `ensureCapacity_smaller` (FrequencySketchTest.java:47-54).
    #[test]
    fn ensure_capacity_smaller() {
        let mut sketch = make_sketch(512);
        let size = sketch.table_len();
        sketch.ensure_capacity((size / 2) as i64);
        assert_eq!(sketch.table_len(), size);
        assert_eq!(sketch.sample_size(), 10 * size as i32);
        assert_eq!(sketch.block_mask(), (size as i32 >> 3) - 1);
    }

    /// Port of `ensureCapacity_larger` (FrequencySketchTest.java:56-63).
    #[test]
    fn ensure_capacity_larger() {
        let mut sketch = make_sketch(512);
        let size = sketch.table_len();
        sketch.ensure_capacity((2 * size) as i64);
        assert_eq!(sketch.table_len(), 2 * size);
        assert_eq!(sketch.sample_size(), 10 * 2 * size as i32);
        assert_eq!(sketch.block_mask(), ((2 * size) as i32 >> 3) - 1);
    }

    /// Port of `increment_once` (FrequencySketchTest.java:74-78).
    #[test]
    fn increment_once() {
        let mut sketch = make_sketch(512);
        sketch.increment(&7);
        assert_eq!(sketch.frequency(&7), 1);
    }

    /// Port of `increment_max` (FrequencySketchTest.java:80-86).
    #[test]
    fn increment_max() {
        let mut sketch = make_sketch(512);
        for _ in 0..20 {
            sketch.increment(&7);
        }
        assert_eq!(sketch.frequency(&7), 15);
    }

    /// Port of `increment_distinct` (FrequencySketchTest.java:88-95).
    #[test]
    fn increment_distinct() {
        let mut sketch = make_sketch(512);
        sketch.increment(&7);
        sketch.increment(&8);
        assert_eq!(sketch.frequency(&7), 1);
        assert_eq!(sketch.frequency(&8), 1);
        assert_eq!(sketch.frequency(&9), 0);
    }

    /// Port of `increment_zero` (FrequencySketchTest.java:97-101).
    #[test]
    fn increment_zero() {
        let mut sketch = make_sketch(512);
        sketch.increment(&0);
        assert_eq!(sketch.frequency(&0), 1);
    }

    /// Port of `reset()` (FrequencySketchTest.java:103-118).
    #[test]
    fn reset() {
        let mut sketch: FrequencySketch<i32> = FrequencySketch::new();
        sketch.ensure_capacity(64);

        let mut did_reset = false;
        for i in 1..(20 * sketch.table_len() as i32) {
            sketch.increment(&i);
            if sketch.size() != i {
                did_reset = true;
                break;
            }
        }
        assert!(did_reset);
        assert!(sketch.size() <= sketch.sample_size() / 2);
    }

    /// Port of `full()` (FrequencySketchTest.java:120-135). Cross-checked bit-for-bit against
    /// `tests/vectors/frequency_sketch_full_{before,after}_reset.hex` in the `vectors` module below.
    #[test]
    fn full() {
        let mut sketch = make_sketch(512);
        sketch.sample_size = i32::MAX;
        for i in 0..100_000i32 {
            sketch.increment(&i);
        }
        for slot in sketch.table.as_ref().unwrap() {
            assert_eq!(slot.count_ones(), 64);
        }

        sketch.reset();
        for slot in sketch.table.as_ref().unwrap() {
            assert_eq!(*slot, super::RESET_MASK);
        }
    }

    /// Port of `heavyHitters()` (FrequencySketchTest.java:137-165). Uses `i32` items in place of Java
    /// `Double` (0.0, 2.0, 4.0, ...) since this port is keyed on `JavaHashCode`, not floats; the
    /// relative-popularity property being tested doesn't depend on the key type.
    #[test]
    fn heavy_hitters() {
        let mut sketch = make_sketch(512);
        for i in 100..100_000i32 {
            sketch.increment(&i);
        }
        for i in (0..10i32).step_by(2) {
            for _ in 0..i {
                sketch.increment(&i);
            }
        }

        // A perfect popularity count yields an array [0, 0, 2, 0, 4, 0, 6, 0, 8, 0]
        let popularity: Vec<i32> = (0..10i32).map(|i| sketch.frequency(&i)).collect();
        for (i, &p) in popularity.iter().enumerate() {
            match i {
                0 | 1 | 3 | 5 | 7 | 9 => assert!(p <= popularity[2]),
                2 => assert!(popularity[2] <= popularity[4]),
                4 => assert!(popularity[4] <= popularity[6]),
                6 => assert!(popularity[6] <= popularity[8]),
                _ => {}
            }
        }
    }

    /// `Caffeine.ceilingPowerOfTwo` spot checks (Caffeine.java:208-211): not part of upstream's
    /// `FrequencySketchTest`, but pinned here since it's exercised transitively by every
    /// `ensure_capacity` call above.
    #[test]
    fn ceiling_power_of_two_spot_checks() {
        assert_eq!(super::ceiling_power_of_two(1), 1);
        assert_eq!(super::ceiling_power_of_two(2), 2);
        assert_eq!(super::ceiling_power_of_two(3), 4);
        assert_eq!(super::ceiling_power_of_two(512), 512);
        assert_eq!(super::ceiling_power_of_two(513), 1024);
    }
}

/// Cross-checks against reference vectors produced by actually running the pinned
/// `caffeine-3.1.8.jar` (`upstream-tools/generate.sh`), not a from-source recompilation or a
/// hand-computed expectation (the port's requirement). Regenerate with
/// `upstream-tools/generate.sh`; `tests/vectors/frequency_sketch_*` should come back byte-identical
/// (verify with `cmp`).
#[cfg(test)]
mod vectors {
    use super::{ceiling_power_of_two, rehash, spread, FrequencySketch};

    const SPREAD_REHASH_CSV: &str = include_str!("../tests/vectors/frequency_sketch_spread_rehash.csv");
    const BASIC_CSV: &str = include_str!("../tests/vectors/frequency_sketch_basic.csv");
    const FULL_BEFORE_HEX: &str = include_str!("../tests/vectors/frequency_sketch_full_before_reset.hex");
    const FULL_AFTER_HEX: &str = include_str!("../tests/vectors/frequency_sketch_full_after_reset.hex");

    /// `VectorGen.writeSpreadRehash`: `FrequencySketch.spread`/`.rehash` called directly (same
    /// package, real jar) on a set of representative `int` inputs including the sign-bit edge cases
    /// Rust's `u32`-based reimplementation has to get right (`Integer.MIN_VALUE`, `0x80000000`, ...).
    #[test]
    fn spread_rehash_matches_jar() {
        let mut rows = 0;
        for line in SPREAD_REHASH_CSV.lines().skip(1) {
            if line.is_empty() {
                continue;
            }
            let mut parts = line.split(',');
            let input: i32 = parts.next().unwrap().parse().unwrap();
            let expected_spread: i32 = parts.next().unwrap().parse().unwrap();
            let expected_rehash: i32 = parts.next().unwrap().parse().unwrap();

            let actual_spread = spread(input);
            assert_eq!(actual_spread, expected_spread, "spread({input})");
            assert_eq!(rehash(actual_spread), expected_rehash, "rehash(spread({input}))");
            rows += 1;
        }
        assert_eq!(rows, 24, "expected the full fixed input list from VectorGen.writeSpreadRehash");
    }

    /// `VectorGen.writeBasicFrequencies`: capacity 64, keys 0..299 (`Integer`, so `hashCode() == key`)
    /// each incremented `key % 5` times, then `frequency(key)` read back — run through the real jar's
    /// `FrequencySketch`, not just this Rust port, so this test fails if the port's `increment`/
    /// `frequency` diverge from upstream even when every Rust-only assertion above still passes.
    #[test]
    fn basic_frequencies_match_jar() {
        let mut sketch: FrequencySketch<i32> = FrequencySketch::new();
        sketch.ensure_capacity(64);
        let key_count = 300i32;
        for k in 0..key_count {
            for _ in 0..(k % 5) {
                sketch.increment(&k);
            }
        }

        let mut rows = 0;
        for line in BASIC_CSV.lines().skip(1) {
            if line.is_empty() {
                continue;
            }
            let mut parts = line.split(',');
            let key: i32 = parts.next().unwrap().parse().unwrap();
            let expected_freq: i32 = parts.next().unwrap().parse().unwrap();
            assert_eq!(sketch.frequency(&key), expected_freq, "frequency({key})");
            rows += 1;
        }
        assert_eq!(rows, key_count);
    }

    /// `VectorGen.writeFullTable`: capacity 512, `sampleSize` forced to `Integer.MAX_VALUE` so
    /// 100,000 increments never triggers a reset, table dumped before and after an explicit
    /// `reset()`. Exact table contents, not just the upstream test's bit-count/`RESET_MASK` summary
    /// assertions (also ported verbatim as `tests::full` above).
    #[test]
    fn full_table_matches_jar() {
        let mut sketch: FrequencySketch<i32> = FrequencySketch::new();
        sketch.ensure_capacity(512);
        assert_eq!(ceiling_power_of_two(512), 512, "vector assumes a 512-entry table");
        sketch.sample_size = i32::MAX;
        for i in 0..100_000i32 {
            sketch.increment(&i);
        }
        assert_table_matches(sketch.table.as_ref().unwrap(), FULL_BEFORE_HEX);

        sketch.reset();
        assert_table_matches(sketch.table.as_ref().unwrap(), FULL_AFTER_HEX);
    }

    fn assert_table_matches(table: &[u64], hex_dump: &str) {
        let expected: Vec<u64> = hex_dump
            .lines()
            .filter(|l| !l.is_empty())
            .map(|l| u64::from_str_radix(l, 16).unwrap())
            .collect();
        assert_eq!(expected.len(), table.len());
        for (i, (&actual, &expected)) in table.iter().zip(expected.iter()).enumerate() {
            assert_eq!(actual, expected, "table[{i}]");
        }
    }
}
